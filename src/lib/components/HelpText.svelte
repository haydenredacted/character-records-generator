	<p>
		Start by clicking New Character. You'll then be able to fill out a variety of information about your character. While drop down menus provide suggested options, you are able to fill in your own entries, such as custom pronouns or chassis brand.
	</p>
	<p>
		Blank fields are omitted from the output automatically, so no rush to finish everything.
	</p>
	<p>
		Characters save to your browser. You can also export to a file or generate a share link: the link itself encodes the full set of records, so functionally it's a save file.
	</p>
	<p>
		Share links let the recipient see a preview of your records, with the option to import the character into their own roster.
	</p>
